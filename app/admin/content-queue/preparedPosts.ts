const SALARY_PILLAR =
  '/blog/post-log-1785841740573';
const GUIDE_LIST = '/blog?category=guide';

function stripHtml(value: string) {
  return value
    .replace(/<[^>]*>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function buildPreparedContent(
  source: PreparedPostSource
) {
  const compactSalaryCopy =
    source.cluster === '연봉·월급';
  const salaryAmountCopy =
    source.seedSlug.startsWith(
      'prepared-2026-salary-'
    );
  const calculatorLink = `<a href="${source.calculatorHref}">${source.calculatorLabel}</a>`;
  const secondLink =
    source.cluster === '연봉·월급'
      ? `<a href="${SALARY_PILLAR}">2026 연봉 실수령액 총정리</a>`
      : `<a href="/money/compound-calc">복리 계산기</a>`;

  return `
    <p>${source.introduction}</p>
    ${
      compactSalaryCopy
        ? ''
        : `<p><strong>${source.keyword}</strong>을 검색하는 사람은 단순한 정의보다 지금 내 통장과 계획에 적용할 수 있는 숫자를 원합니다. 그래서 이 글은 계산 기준, 실제 활용법, 놓치기 쉬운 조건을 한 번에 확인할 수 있도록 정리했습니다.</p>`
    }

    <blockquote>
      <p><strong>${source.keyword} 핵심 요약</strong></p>
      <ul>
        ${source.summary.map((item) => `<li>${item}</li>`).join('')}
      </ul>
    </blockquote>

    ${
      compactSalaryCopy
        ? `<h3>${source.keyword} 계산 기준</h3>`
        : ''
    }

    ${source.sections
      .map(
        (section, index) => `
          <h2>${
            index === 0
              ? `${source.keyword}, ${section.heading}`
              : section.heading
          }</h2>
          ${section.paragraphs
            .map(
              (paragraph) => `<p>${paragraph}</p>`
            )
            .join('')}
        `
      )
      .join('')}

    <h2>${source.keyword} 최종 체크리스트</h2>
    ${
      compactSalaryCopy
        ? `<p><strong>${source.keyword}</strong> 결과는 아래 조건을 함께 확인해야 정확해집니다.</p>`
        : ''
    }
    ${
      compactSalaryCopy
        ? ''
        : '<p>숫자를 확인했다면 아래 세 가지를 마지막으로 점검해보세요. 계산 결과보다 중요한 것은 어떤 가정을 넣었는지, 실제 계약이나 계좌 조건과 얼마나 다른지를 아는 것입니다.</p>'
    }
    <ul>
      ${source.checklist.map((item) => `<li>${item}</li>`).join('')}
    </ul>

    ${
      compactSalaryCopy
        ? ''
        : `<p>${source.keyword}은 정답을 맞히는 문제가 아니라 선택지를 비교하는 도구입니다. 한 가지 숫자만 보지 말고 보수적·기준·낙관적 조건을 각각 넣어보면 현실적인 범위를 잡을 수 있습니다. 특히 세금, 보험료, 투자수익은 개인 조건과 시점에 따라 달라질 수 있으므로 실제 명세서나 금융상품 안내도 함께 확인하는 것이 안전합니다.</p>`
    }

    <h2>직접 계산해보기</h2>
    <p>${calculatorLink}에서 내 조건을 입력해보세요. 결과를 저장해두고 실제 급여명세서나 계좌 잔액과 비교하면 다음 계획을 더 구체적으로 세울 수 있습니다.</p>

    <blockquote>
      <p><strong>다음 읽을 글</strong></p>
      <p>1. ${calculatorLink}</p>
      <p>2. ${secondLink}</p>
      <p>3. <a href="${GUIDE_LIST}">호행처럼 각종 정보 전체 보기</a></p>
    </blockquote>

    <h2>호진님이라면 어떤 기준을 먼저 볼까요?</h2>
    <p>① ${source.questions[0]}</p>
    <p>② ${source.questions[1]}</p>

    <p><small>${
      compactSalaryCopy
        ? salaryAmountCopy
          ? '예상치이며 개인 조건에 따라 달라집니다.'
          : '급여 계산은 회사 신고 기준·비과세 수당·공제대상가족·원천징수 방식에 따라 실제 결과와 달라질 수 있습니다.'
        : '이 글의 계산 결과는 이해를 돕기 위한 예상치입니다. 투자는 수익률·세금·수수료·시장 변동에 따라 실제 결과가 달라질 수 있습니다.'
    } 확인 기준일: 2026년 8월.</small></p>
  `
    .trim()
    .replace(/\n\s+/g, '\n');
}

